#!/bin/bash
set -euxo pipefail

ROOT_DIR="$(realpath "$(dirname "$0")/../..")"
INSTALL_DIR="/srv/vacuula"
BACKUP_DIR="/srv/vacuula-backups"

# Stop service, optionally back up existing data
systemctl stop vacuula 2>/dev/null || true

if [[ -d "$INSTALL_DIR/data" ]]; then
    read -r -p "Back up existing data first? [Y/n] " answer
    if [[ ! "$answer" =~ ^[Nn] ]]; then
        mkdir -p /srv/vacuula-backups
        tar -czf "/srv/vacuula-backups/data-$(date +%Y%m%d-%H%M%S).tar.gz" -C "$INSTALL_DIR" data
        echo "Backup saved to /srv/vacuula-backups"
    fi
fi

# Version detection (from server/pyproject.toml)
detect_version() {
    local default="0.0.0-dev"
    local version

    version="$(sed -nE 's/^version = "(.*)"/\1/p' "$ROOT_DIR/server/pyproject.toml" 2>/dev/null | head -1)"
    version="${version:-$default}"

    # Local changes -> -dirty
    if [[ -n "$(git -C "$ROOT_DIR" status --porcelain 2>/dev/null)" ]]; then
        version="${version}-dirty"
    fi

    echo "$version"
}

APP_VERSION="$(detect_version)"
echo "Installing Vacuula version: $APP_VERSION"

sleep 1

# System dependencies
apt-get update
apt-get install -y \
    curl \
    openssl \
    nodejs \
    npm

# uv
if ! command -v uv >/dev/null 2>&1; then
    curl -LsSf https://astral.sh/uv/install.sh | UV_UNMANAGED_INSTALL=/usr/local/bin sh
fi

# Service user
if ! id vacuula >/dev/null 2>&1; then
    useradd --system --home-dir "$INSTALL_DIR" --shell /usr/sbin/nologin vacuula
fi

# Frontend
cd "$ROOT_DIR/app"

corepack enable
npm install -g pnpm
pnpm approve-builds @parcel/watcher
pnpm install --frozen-lockfile
pnpm vite build

# Install application
mkdir -p "$INSTALL_DIR"

rm -rf "$INSTALL_DIR/src"
rm -rf "$INSTALL_DIR/migrations"
rm -rf "$INSTALL_DIR/web"

cp -r "$ROOT_DIR/server/src" "$INSTALL_DIR/src"
cp -r "$ROOT_DIR/server/migrations" "$INSTALL_DIR/migrations"
cp "$ROOT_DIR/server/alembic.ini" "$INSTALL_DIR/alembic.ini"

# Build version
cat > "$INSTALL_DIR/src/vacuula_server/_build_version.py" <<EOF
APP_VERSION = "${APP_VERSION}" # version is auto-generated by install script
EOF

# Python project files
cp "$ROOT_DIR/server/pyproject.toml" \
   "$ROOT_DIR/server/uv.lock" \
   "$INSTALL_DIR/"

mkdir -p "$INSTALL_DIR/ssl"
cp "$ROOT_DIR/server/ssl/vacuula.cnf" "$INSTALL_DIR/ssl/vacuula.cnf"

cp -r "$ROOT_DIR/app/dist" "$INSTALL_DIR/web"

# Python dependencies
export UV_PYTHON_INSTALL_DIR=/opt/uv-python
cd "$INSTALL_DIR"
uv sync --frozen --no-dev --no-editable --reinstall-package vacuula-server

# Install systemd service
cp "$ROOT_DIR/build/lxc/vacuula.service" /etc/systemd/system/vacuula.service

systemctl daemon-reload
systemctl enable vacuula

# Database migrations
cd "$INSTALL_DIR"
.venv/bin/alembic upgrade head

# Perms
chown -R vacuula:vacuula "$INSTALL_DIR/data"

# Start
systemctl restart vacuula

echo "Vacuula ${APP_VERSION} installed. Check status with: systemctl status vacuula and logs with: journalctl -u vacuula -f"