#!/bin/bash
set -euxo pipefail

ROOT_DIR="$(dirname "$0")/.."
INSTALL_DIR="/srv/vacuula"

# Version detection
detect_version() {
  local default="0.0.0-dev"
  local msg version=""

  # No git, or not a git checkout -> default
  command -v git >/dev/null 2>&1 || { echo "$default"; return; }
  git -C "$ROOT_DIR" rev-parse --is-inside-work-tree >/dev/null 2>&1 || { echo "$default"; return; }

  # Same tags as the GitHub workflow
  msg="$(git -C "$ROOT_DIR" log -1 --pretty=%B 2>/dev/null || true)"
  if [[ "$msg" =~ release:([0-9A-Za-z._-]+) ]]; then
    version="${BASH_REMATCH[1]}"
  elif [[ "$msg" =~ dbuild:([0-9A-Za-z._-]+) ]]; then
    version="${BASH_REMATCH[1]}"
  fi

  # strep
  version="${version%%[._-]}"
  if [[ -z "$version" ]]; then
    version="$default"
  fi

  # Local changes -> -dirty
  if [[ -n "$(git -C "$ROOT_DIR" status --porcelain 2>/dev/null)" ]]; then
    version="${version}-dirty"
  fi

  echo "$version"
}

APP_VERSION="$(detect_version)"
echo "Installing Vacuula version: $APP_VERSION"

# System dependencies
apt-get update
apt-get install -y \
    curl \
    openssl \
    python3 \
    python3-pip \
    nodejs \
    npm

# Frontend
cd "$ROOT_DIR/app"

corepack enable
pnpm approve-builds @parcel/watcher
pnpm install --frozen-lockfile
pnpm vite build

# Python dependencies
cd "$ROOT_DIR/server"
GIT_HASH=$(git rev-parse --short HEAD)
cat > src/_build_version.py <<EOF
APP_VERSION = "${APP_VERSION}" # version is auto-generated by GH Actions
EOF

python3 -m pip install --no-cache-dir --upgrade pip
python3 -m pip install --no-cache-dir -r requirements.txt

# Install application
mkdir -p "$INSTALL_DIR"

rm -rf "$INSTALL_DIR/src"
rm -rf "$INSTALL_DIR/migrations"
rm -rf "$INSTALL_DIR/web"

cp -r "$ROOT_DIR/server/src" "$INSTALL_DIR/src"
cp -r "$ROOT_DIR/server/migrations" "$INSTALL_DIR/migrations"
cp "$ROOT_DIR/server/alembic.ini" "$INSTALL_DIR/alembic.ini"

mkdir -p "$INSTALL_DIR/data/ssl"

cp "$ROOT_DIR/server/data/ssl/vacuula.cnf" \
    "$INSTALL_DIR/data/ssl/vacuula.cnf"

cp -r "$ROOT_DIR/app/dist" "$INSTALL_DIR/web"

# Install systemd service
cp "$ROOT_DIR/vacuula.service" /etc/systemd/system/vacuula.service

systemctl daemon-reload
systemctl enable vacuula

# Database migrations
cd "$INSTALL_DIR"
alembic upgrade head

# Start
systemctl restart vacuula

echo "Vacuula installed successfully."